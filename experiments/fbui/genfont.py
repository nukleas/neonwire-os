#!/usr/bin/env python3
"""Bake a monospace TTF into an anti-aliased C bitmap-font header for neofb.

Emits font_neon.h with:
  FONT_W, FONT_H          cell dimensions (pixels)
  FONT_FIRST, FONT_LAST   glyph range (ASCII 32..126)
  font_alpha[N * FONT_W*FONT_H]   coverage 0..255, row-major per glyph

Coverage bytes let neofb alpha-blend glyphs in any neon colour and scale them
by integer factors for headings.
"""
from __future__ import annotations

import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/TTF/JetBrainsMonoNerdFontMono-Bold.ttf"
FALLBACK = "/usr/share/fonts/TTF/JetBrainsMonoNerdFontMono-Regular.ttf"
PT = 18
FIRST, LAST = 32, 126


def load_font() -> ImageFont.FreeTypeFont:
    for p in (FONT_PATH, FALLBACK):
        try:
            return ImageFont.truetype(p, PT)
        except OSError:
            continue
    print("no JetBrains Mono found; falling back to DejaVu", file=sys.stderr)
    return ImageFont.truetype("/usr/share/fonts/noto/NotoSansMono-Bold.ttf", PT)


def main() -> None:
    font = load_font()
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    cell_w = round(font.getlength("M"))
    glyphs = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (cell_w, cell_h), 0)
        d = ImageDraw.Draw(img)
        d.text((0, 0), chr(code), font=font, fill=255, anchor="la")
        glyphs.append(list(img.getdata()))

    n = len(glyphs)
    out = []
    out.append("/* Generated by genfont.py — JetBrains Mono, do not edit. */")
    out.append("#ifndef FONT_NEON_H")
    out.append("#define FONT_NEON_H")
    out.append(f"#define FONT_W {cell_w}")
    out.append(f"#define FONT_H {cell_h}")
    out.append(f"#define FONT_FIRST {FIRST}")
    out.append(f"#define FONT_LAST {LAST}")
    out.append(f"#define FONT_COUNT {n}")
    out.append("static const unsigned char font_alpha[FONT_COUNT * FONT_W * FONT_H] = {")
    flat = []
    for g in glyphs:
        flat.extend(g)
    for i in range(0, len(flat), 20):
        out.append("  " + ",".join(str(v) for v in flat[i : i + 20]) + ",")
    out.append("};")
    out.append("#endif")

    with open("font_neon.h", "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"font_neon.h: cell {cell_w}x{cell_h}, {n} glyphs, {len(flat)} bytes")


if __name__ == "__main__":
    main()
