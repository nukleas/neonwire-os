#!/usr/bin/env python3
"""Bake a monospace TTF into font data for the neon-gfx Rust engine.

Copy of experiments/fbui/genfont.py with a Rust output mode. Emits into
neon-gfx/src/:
  font_data.rs    FONT_W/FONT_H/FONT_FIRST/FONT_LAST consts + include_bytes! glue
  font_alpha.bin  coverage 0..255, row-major per glyph, glyphs FIRST..=LAST

Both files are CHECKED IN so cargo builds need neither PIL nor the TTF.
Re-run only to change the font/size:  python3 tools/genfont.py
"""
from __future__ import annotations

import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/TTF/JetBrainsMonoNerdFontMono-Bold.ttf"
FALLBACK = "/usr/share/fonts/TTF/JetBrainsMonoNerdFontMono-Regular.ttf"
PT = 18
FIRST, LAST = 32, 126
OUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "neon-gfx" / "src"


def load_font() -> ImageFont.FreeTypeFont:
    for p in (FONT_PATH, FALLBACK):
        try:
            return ImageFont.truetype(p, PT)
        except OSError:
            continue
    print("no JetBrains Mono found; falling back to Noto", file=sys.stderr)
    return ImageFont.truetype("/usr/share/fonts/noto/NotoSansMono-Bold.ttf", PT)


def main() -> None:
    font = load_font()
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    cell_w = round(font.getlength("M"))
    flat = bytearray()
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (cell_w, cell_h), 0)
        d = ImageDraw.Draw(img)
        d.text((0, 0), chr(code), font=font, fill=255, anchor="la")
        flat.extend(img.getdata())

    (OUT_DIR / "font_alpha.bin").write_bytes(flat)
    n = LAST - FIRST + 1
    rs = f"""// Generated by tools/genfont.py — JetBrains Mono Bold {PT}pt. Do not edit.
pub const FONT_W: usize = {cell_w};
pub const FONT_H: usize = {cell_h};
pub const FONT_FIRST: u8 = {FIRST};
pub const FONT_LAST: u8 = {LAST};
pub static FONT_ALPHA: &[u8; {n} * FONT_W * FONT_H] = include_bytes!("font_alpha.bin");
"""
    (OUT_DIR / "font_data.rs").write_text(rs)
    print(f"font_data.rs + font_alpha.bin: cell {cell_w}x{cell_h}, {n} glyphs, {len(flat)} bytes")


if __name__ == "__main__":
    main()
